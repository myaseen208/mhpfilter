test_that("loss, gains, weights and schedules", {
  l <- hp_loss(x = 55, lambda = 100)
  expect_equal(l$total, sum(l$loss$loss))
  expect_equal(round(l$total, 3), 1.735)
  expect_equal(l$loss$loss[28L], 0)
  expect_s3_class(plot(l), "ggplot")
  expect_output(print(l), "End-point loss")
  s <- hp_schedule(T = 50, lambda = 100, alpha = 10, k = 20, power = 1)
  expect_identical(s[c(1, 20, 21, 30, 31, 50)], c(300, 110, 100, 100, 110, 300))
  expect_identical(hp_schedule(T = 50, lambda = 100, alpha = 2, k = 3, power = 2)[1:4], c(118, 108, 102, 100))
  expect_error(hp_schedule(T = 20, lambda = 100, alpha = 1, k = 11), "too large")
  g <- hp_gain(x = 50, lambda = 100, rows = c(1, 25))
  expect_identical(g$rows, c(1L, 25L))
  expect_s3_class(plot(g), "ggplot")
  w <- hp_weights(x = 50, lambda = 100)
  expect_identical(w$rows, c(1L, 3L, 25L, 26L, 47L, 49L))
  expect_s3_class(plot(w), "ggplot")
  expect_error(hp_loss(x = 50, lambda = rep(1, 7)), "length")
  f <- fmhp_filter(exp(cumsum(rep(0.01, 60)) + sin(1:60 / 3) / 50), as_dt = FALSE)
  expect_equal(hp_loss(f)$total, sum(hp_loss(x = 60, lambda = f$lambda_t)$loss$loss))
})
