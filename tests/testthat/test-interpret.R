data(us_macro, package = "mhpfilter")
gdp <- ts(us_macro$gdp, start = c(1959, 1), frequency = 4)

test_that("interpretations of every result", {
  m <- mhp_filter(log(gdp), max_lambda = 3000, as_dt = FALSE)
  it <- mhp_interpret(m)
  expect_s3_class(it, "mhp_interpretation")
  expect_match(it$headline, "lambda = 683")
  expect_match(it$headline, "below the conventional 1,600")
  expect_match(paste(it$findings, collapse = " "), "Q")
  f <- fmhp_filter(gdp, as_dt = FALSE)
  expect_match(mhp_interpret(f)$headline, "cut the end-point loss")
  expect_match(mhp_interpret(hp_filter(log(gdp), as_dt = FALSE))$headline, "lambda = 1,600")
  expect_match(mhp_interpret(mhp_filter(log(gdp), max_lambda = 3000))$headline, "683")
  expect_match(mhp_interpret(hp_loss(x = 55, lambda = 100))$headline, "1.7345")
  for (o in list(hp_gain(x = 50, lambda = 100), hp_weights(x = 50, lambda = 100)))
    expect_true(nzchar(mhp_interpret(o)$headline))
  expect_true(any(grepl("^## ", format(it, style = "markdown"))))
  expect_output(print(it), "Sources:")
  expect_error(mhp_interpret(1:3), "result")
  mx <- mhp_filter(log(gdp), max_lambda = 300, as_dt = FALSE)
  expect_match(paste(mhp_interpret(mx)$cautions, collapse = " "), "max_lambda")
})
