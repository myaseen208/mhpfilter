test_that("designs, simulated series and the power comparison", {
  d <- mhp_designs()
  expect_identical(dim(d), c(30L, 4L))
  expect_equal(d$sd_ratio[c(1, 6, 26, 30)], c(10, 5, 10, 0.5))
  s <- mhp_simulate(T = 200, seed = 1)
  expect_identical(dim(s), c(200L, 4L))
  expect_equal(s$x, s$trend + s$cycle)
  expect_identical(nrow(mhp_simulate(T = 200, aggregate = "sum", seed = 1)), 50L)
  a <- mhp_simulate(T = 200, aggregate = "average", trend = "nonlinear", seed = 2)
  b <- mhp_simulate(T = 200, aggregate = "sum", trend = "nonlinear", seed = 2)
  expect_equal(b$x, 4 * a$x)
  expect_identical(mhp_simulate(T = 40, seed = 3), mhp_simulate(T = 40, seed = 3))
  expect_error(mhp_simulate(ar = c(1.2, 0.5)), "stationary")
  sim <- fmhp_simulation(designs = d[c(3, 23)], n_rep = 2, T = 100, seed = 1)
  expect_identical(nrow(sim$rmse), 6L)
  expect_identical(nrow(sim$power), 2L)
  expect_true(all(sim$rmse$rmse > 0))
  expect_s3_class(plot(sim), "ggplot")
  expect_output(print(sim), "Average RMSE")
})
