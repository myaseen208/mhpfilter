data(us_macro, package = "mhpfilter")
gdp <- ts(us_macro$gdp, start = c(1959, 1), frequency = 4)

test_that("hp_filter and mhp_filter keep the results of version 0.1.0 and add the new ones at the end", {
  h <- hp_filter(log(us_macro$gdp))
  expect_s3_class(h, "data.table")
  expect_identical(names(h), c("original", "trend", "cycle"))
  expect_identical(attr(h, "lambda"), 1600)
  m <- mhp_filter(log(us_macro$gdp), max_lambda = 3000)
  expect_identical(attr(m, "lambda"), 683L)
  ml <- mhp_filter(log(us_macro$gdp), max_lambda = 3000, as_dt = FALSE)
  expect_s3_class(ml, c("mhp_mhp", "mhp", "mhp_result"))
  expect_identical(names(ml)[1:5], c("original", "trend", "cycle", "lambda", "gcv"))
  expect_length(ml$gcv_path, 3000L)
  expect_equal(ml$cycle, m$cycle)
  expect_identical(get_lambda(m), get_lambda(ml))
  expect_identical(get_gcv(m), get_gcv(ml))
})

test_that("ts input, log scale and the exact criterion", {
  m <- mhp_filter(gdp, max_lambda = 3000, as_dt = FALSE, log_scale = TRUE)
  expect_equal(m$time, as.numeric(time(gdp)))
  expect_identical(m$frequency, 4)
  expect_equal(m$trend * exp(m$cycle_log), as.numeric(gdp), tolerance = 1e-10)
  expect_equal(m$cycle, as.numeric(gdp) - m$trend)
  d <- mhp_filter(gdp, max_lambda = 3000, log_scale = TRUE)
  expect_true("time" %in% names(d))
  expect_warning(e <- mhp_filter(log(gdp), max_lambda = 500, as_dt = FALSE, criterion = "exact"), "lower end")
  expect_identical(e$lambda, 1L)
  expect_error(hp_filter(c(1, NA, 3, 4, 5, 6)), "missing")
  expect_error(hp_filter(1:3), "too short")
  expect_error(hp_filter(-(1:10), log_scale = TRUE), "positive")
  expect_error(mhp_filter("a"), "numeric")
})

test_that("fmhp_filter: settings, fixed lambda, both forms, errors", {
  f <- fmhp_filter(gdp, as_dt = FALSE)
  expect_s3_class(f, c("mhp_fmhp", "mhp", "mhp_result"))
  expect_identical(f$scheme, "quadratic")
  expect_identical(c(f$lambda_mhp, f$lambda), c(683L, 1448L))
  expect_identical(f$k, 22L)
  expect_length(f$lambda_t, length(gdp))
  expect_identical(nrow(f$schemes), 2L)
  d <- fmhp_filter(gdp)
  expect_identical(attr(d, "lambda"), f$lambda)
  expect_identical(attr(d, "scheme"), "quadratic")
  fx <- fmhp_filter(gdp, lambda = 1600, as_dt = FALSE)
  expect_identical(fx$lambda, 1600)
  expect_true(is.na(fx$gcv))
  fd <- fmhp_filter(gdp, form = "differences", schemes = "linear", as_dt = FALSE)
  expect_length(fd$lambda_t, length(gdp) - 2L)
  expect_identical(fd$scheme, "linear")
  expect_error(fmhp_filter(exp(cumsum(rnorm(25, 0.1)))), "too short")
  expect_error(fmhp_filter(gdp, schemes = "cubic"), "schemes")
  expect_error(fmhp_filter(gdp, form = "columns"), "form")
})

test_that("every filter is an S3 generic and stores the call as written", {
  for (f in c("hp_filter", "mhp_filter", "fmhp_filter", "mhp_batch", "fmhp_batch", "mhp_compare", "batch_compare",
              "fmhp_compare", "hp_weights", "hp_gain", "hp_loss", "get_lambda", "get_gcv", "mhp_interpret",
              "mhp_cite", "mhp_save"))
    expect_true(is.function(getS3method(f, "default")), info = f)
  m <- mhp_filter(log(us_macro$gdp), max_lambda = 100, as_dt = FALSE)
  expect_identical(deparse(attr(m, "call")[[1L]]), "mhp_filter")
})

test_that("printing and plots", {
  f <- fmhp_filter(gdp, as_dt = FALSE)
  expect_output(print(f), "Fully modified HP Filter Result")
  expect_output(print(f), "Sources:")
  m <- mhp_filter(log(gdp), max_lambda = 3000, as_dt = FALSE)
  expect_output(print(m), "Optimal lambda: 683")
  for (w in c("decomposition", "lambda", "loss")) expect_s3_class(plot(f, which = w), "ggplot")
  expect_s3_class(plot(m, which = "gcv"), "ggplot")
  expect_s3_class(ggplot2::autoplot(m), "ggplot")
  expect_error(plot(m, which = "lambda"), "fully modified")
  expect_s3_class(plot_comparison(log(us_macro$gdp), show_cycle = TRUE, fmhp = TRUE), "ggplot")
})
